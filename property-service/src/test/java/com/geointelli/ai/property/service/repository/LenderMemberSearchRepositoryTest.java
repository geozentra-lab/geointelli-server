package com.geointelli.ai.property.service.repository;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.List;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.jdbc.AutoConfigureTestDatabase;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import com.geointelli.ai.property.service.entity.LenderOrganizationMember;

/** Membership of the accounts an owner's search found, read in one query (H2 in PostgreSQL mode, table as in V24). */
@DataJpaTest(showSql = false, properties = {
    "spring.datasource.url=jdbc:h2:mem:lender-member-search;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
    "spring.jpa.hibernate.ddl-auto=none",
    "spring.flyway.enabled=false"
})
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@ActiveProfiles("test")
class LenderMemberSearchRepositoryTest {
    @Autowired LenderOrganizationMemberRepository memberships;
    @Autowired JdbcTemplate jdbc;

    @BeforeEach
    void memberships() {
        jdbc.execute("DROP TABLE IF EXISTS lender_organization_members");
        jdbc.execute("CREATE TABLE lender_organization_members ("
            + " id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " organization_id BIGINT NOT NULL, user_id BIGINT NOT NULL,"
            + " CONSTRAINT uq_lender_membership UNIQUE (organization_id, user_id))");
        jdbc.update("INSERT INTO lender_organization_members (organization_id, user_id)"
            + " VALUES (10, 8), (10, 9), (11, 12)");
    }

    @Test
    @DisplayName("Only this organization's memberships, and only those of the accounts asked about")
    void membershipsOfTheAccountsFound() {
        assertThat(memberships.findByOrganizationIdAndUserIdIn(10L, List.of(8L, 12L, 40L)))
            .extracting(LenderOrganizationMember::getUserId)
            .containsExactly(8L);
        assertThat(memberships.findByOrganizationIdAndUserIdIn(11L, List.of(8L, 9L))).isEmpty();
    }
}
