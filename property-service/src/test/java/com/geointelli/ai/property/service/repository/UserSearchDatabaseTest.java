package com.geointelli.ai.property.service.repository;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.postgresql.ds.PGSimpleDataSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import com.geointelli.ai.property.service.util.UserSearch;

/**
 * Opt-in checks of migration V53 and {@link UserRepository#SEARCH} on a real PostgreSQL, with the same rules as
 * MarketEvidenceDatabaseTest: a schema of its own on a dedicated local test database whose name ends with _test,
 * dropped afterwards; never the application's database.
 * <p>
 * Measured once by hand on PostgreSQL 16 (Windows laptop) with 200,000 generated users, generic plans, no parallel
 * workers: under 1 ms for a prefix matching a dozen rows, about 60 ms for one matching 20,000. A LIKE + NOT EXISTS
 * version took 1.4 s on the 20,000 (Postgres hashed the whole table for NOT EXISTS) and, once the prepared statement
 * went generic, could no longer use its LIKE indexes and read the whole table.
 */
@EnabledIfEnvironmentVariable(named = "ENVIRONMENTAL_TEST_DB_URL", matches = ".+")
class UserSearchDatabaseTest {

    private static final String SCHEMA = "user_search_test_" + UUID.randomUUID().toString().replace("-", "");
    private static final Path V53 = Path.of("src/main/resources/db/migration/V53__add_user_search_columns.sql");

    private static JdbcTemplate jdbc;
    private static NamedParameterJdbcTemplate named;

    @BeforeAll
    static void prepare() throws Exception {
        String url = System.getenv("ENVIRONMENTAL_TEST_DB_URL");
        if (!url.matches("jdbc:postgresql://(localhost|127\\.0\\.0\\.1):[0-9]+/[A-Za-z0-9_]+_test")) {
            throw new IllegalStateException("Only a dedicated local database whose name ends with _test is allowed");
        }
        PGSimpleDataSource dataSource = new PGSimpleDataSource();
        dataSource.setUrl(url);
        dataSource.setUser(System.getenv("DB_USER"));
        dataSource.setPassword(System.getenv("DB_PASSWORD"));
        try (Connection connection = dataSource.getConnection(); var statement = connection.createStatement()) {
            statement.execute("CREATE SCHEMA " + SCHEMA);
        }
        dataSource.setCurrentSchema(SCHEMA);
        jdbc = new JdbcTemplate(dataSource);
        named = new NamedParameterJdbcTemplate(jdbc);
        // users as Hibernate created it
        jdbc.execute("CREATE TABLE users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " keycloak_user_id varchar(255) NOT NULL UNIQUE, username varchar(255), email varchar(255),"
            + " first_name varchar(255), last_name varchar(255), persona varchar(40),"
            + " onboarding_completed_at timestamptz, created_at timestamp(6) NOT NULL, updated_at timestamp(6) NOT NULL)");
        account(5, "jane@example.com", "Old", "Name");          // older row of Jane's email
        account(7, "john_doe@example.com", "John", "Smith");
        account(8, "johnny@example.com", "Johnny", "Appleseed");
        account(9, "dana@bank.example", "Dana", "Jonas");
        account(10, null, "Danny", null);
        account(11, "x@example.com", null, "Daniels");
        account(12, "oldname@example.com", "Olga", "Ford");     // older row of the next one's email
        account(13, "OLDNAME@example.com", "Peter", "Pan");
        // enough other accounts for the planner to prefer the indexes; none starts with a prefix searched below
        jdbc.update("INSERT INTO users (id, keycloak_user_id, email, first_name, last_name, persona, created_at,"
            + " updated_at) SELECT g, 'kc-' || g, 'filler' || g || '@example.org', 'Filler', 'Row' || g, 'USER',"
            + " now(), now() FROM generate_series(1000, 5999) g");
        jdbc.execute(Files.readString(V53));
        jdbc.execute(Files.readString(V53));                     // applying it again changes nothing
        account(41, "Jane@Example.com", "Jane", "Doe");         // inserted after the migration
    }

    private static void account(long id, String email, String firstName, String lastName) {
        jdbc.update("INSERT INTO users (id, keycloak_user_id, username, email, first_name, last_name, persona,"
            + " created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, 'USER', now(), now())",
            id, "kc-" + id, email, email, firstName, lastName);
    }

    @AfterAll
    static void cleanup() {
        // SCHEMA is generated here, never supplied by a caller; the database URL is checked above.
        if (jdbc != null) jdbc.execute("DROP SCHEMA IF EXISTS " + SCHEMA + " CASCADE");
    }

    private static String search(String q, int size) {
        String prefix = UserSearch.prefix(q);
        List<Long> ids = named.query(UserRepository.SEARCH,
            Map.of("prefix", prefix, "prefixEnd", UserSearch.upperBound(prefix), "size", size),
            (row, index) -> row.getLong("id"));
        return ids.stream().map(String::valueOf).reduce((a, b) -> a + "," + b).orElse("");
    }

    @Test
    @DisplayName("Same suggestions as on H2: prefixes, newest row of each email, literal _ and %, size")
    void sameSuggestionsAsH2() {
        assertThat(search("jo", 10)).isEqualTo("9,7,8");
        assertThat(search("DAN", 10)).isEqualTo("9,11,10");
        assertThat(search("JOHNNY@Ex", 10)).isEqualTo("8");
        assertThat(search("jane do", 10)).isEqualTo("41");
        assertThat(search("john  smi", 10)).isEqualTo("7");
        assertThat(search("doe", 10)).isEqualTo("41");
        assertThat(search("ane", 10)).isEmpty();
        assertThat(search("smith john", 10)).isEmpty();
        assertThat(search("jane", 10)).isEqualTo("41");
        assertThat(search("old", 10)).isEqualTo("13");
        assertThat(search("olg", 10)).isEmpty();
        assertThat(search("john_", 10)).isEqualTo("7");
        assertThat(search("jo%", 10)).isEmpty();
        assertThat(search("jo", 2)).isEqualTo("9,7");
    }

    @Test
    @DisplayName("The search columns follow every insert and update")
    void columnsFollowChanges() {
        jdbc.update("UPDATE users SET last_name = 'Rivera', email = 'Cleo@Bank.example' WHERE id = 8");
        try {
            assertThat(search("johnny ri", 10)).isEqualTo("8");
            assertThat(search("cleo@", 10)).isEqualTo("8");
            assertThat(search("johnny@", 10)).isEmpty();
        } finally {
            jdbc.update("UPDATE users SET last_name = 'Appleseed', email = 'johnny@example.com' WHERE id = 8");
        }
        assertThat(jdbc.queryForObject("SELECT full_name_search FROM users WHERE id = 11", String.class))
            .isEqualTo(" daniels");
    }

    @Test
    @DisplayName("A generic plan of the prepared statement still finds the rows through the three indexes")
    void genericPlanUsesTheIndexes() {
        String prepared = UserRepository.SEARCH.replace(":prefixEnd", "$2").replace(":prefix", "$1")
            .replace(":size", "$3");
        List<String> plan = jdbc.execute((Connection connection) -> {
            try (Statement statement = connection.createStatement()) {
                statement.execute("SET enable_seqscan = off");          // 5,000 rows are still cheap to scan
                statement.execute("SET plan_cache_mode = force_generic_plan");
                statement.execute("PREPARE search_users(text, text, int) AS " + prepared);
                List<String> lines = new ArrayList<>();
                try (ResultSet rows = statement.executeQuery("EXPLAIN (COSTS OFF) EXECUTE search_users('an', 'ao', 10)")) {
                    while (rows.next()) lines.add(rows.getString(1));
                }
                statement.execute("DEALLOCATE search_users");
                return lines;
            }
        });

        String text = String.join("\n", plan);
        assertThat(text).contains("Bitmap Index Scan on idx_users_email_search",
            "Bitmap Index Scan on idx_users_full_name_search", "Bitmap Index Scan on idx_users_last_name_search",
            "Index Cond: ((full_name_search >= $1) AND (full_name_search < $2))",
            "Index Scan using idx_users_email_search on users n");
        assertThat(text).doesNotContain("Seq Scan");
    }
}
