-- Realtor license submissions checked against the state registry (SCRUM-198 / SCRUM-200).
-- One row per submission: a rejected submission is never edited, the user submits a new row instead,
-- so the history of decisions is preserved. Two independent groups of columns:
--   * auto_check_*: what an automatic registry check found (future integration); informative only,
--     it may run before a human looks at the row.
--   * decision columns (status, decision_method, reviewed_by_user_id, decided_at, registry_source,
--     rejection_reason): the final outcome, written by a GeoZentra admin (SCRUM-199, MANUAL) or by
--     the automatic check itself (AUTOMATIC, no reviewer). A row may carry both: the API checked
--     first, then an admin decided.

CREATE TABLE realtor_license_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    license_holder_name VARCHAR(160) NOT NULL CHECK (BTRIM(license_holder_name) <> ''),
    licensing_state CHAR(2) NOT NULL CHECK (licensing_state ~ '^[A-Z]{2}$'),
    license_number VARCHAR(40) NOT NULL CHECK (BTRIM(license_number) <> ''),
    license_expiration_date DATE,
    brokerage_name VARCHAR(160),
    work_email VARCHAR(254),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING_REVIEW'
        CHECK (status IN ('PENDING_REVIEW', 'VERIFIED', 'REJECTED')),
    auto_check_result VARCHAR(20) CHECK (auto_check_result IN ('MATCH', 'NO_MATCH', 'INCONCLUSIVE')),
    auto_checked_at TIMESTAMP WITH TIME ZONE,
    auto_check_source VARCHAR(200),
    auto_check_note VARCHAR(500),
    rejection_reason VARCHAR(500),
    decision_method VARCHAR(20) CHECK (decision_method IN ('MANUAL', 'AUTOMATIC')),
    reviewed_by_user_id BIGINT REFERENCES users(id),
    decided_at TIMESTAMP WITH TIME ZONE,
    registry_source VARCHAR(200),
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- An automatic check, when it ran, records when and where it looked.
    CONSTRAINT ck_realtor_license_auto_check CHECK (
        (auto_check_result IS NULL AND auto_checked_at IS NULL AND auto_check_source IS NULL AND auto_check_note IS NULL)
        OR (auto_check_result IS NOT NULL AND auto_checked_at IS NOT NULL
            AND auto_check_source IS NOT NULL AND BTRIM(auto_check_source) <> '')
    ),
    -- A pending row carries no decision. A decided row carries the method, the time and the registry
    -- consulted; a MANUAL decision also carries the reviewer; an AUTOMATIC decision needs the auto check
    -- that produced it; a rejection needs a reason.
    CONSTRAINT ck_realtor_license_decision CHECK (
        (status = 'PENDING_REVIEW' AND decision_method IS NULL AND reviewed_by_user_id IS NULL
            AND decided_at IS NULL AND registry_source IS NULL AND rejection_reason IS NULL)
        OR (status IN ('VERIFIED', 'REJECTED')
            AND decision_method IS NOT NULL AND decided_at IS NOT NULL
            AND registry_source IS NOT NULL AND BTRIM(registry_source) <> ''
            AND (decision_method <> 'MANUAL' OR reviewed_by_user_id IS NOT NULL)
            AND (decision_method <> 'AUTOMATIC' OR auto_check_result IS NOT NULL)
            AND ((status = 'VERIFIED' AND rejection_reason IS NULL)
                OR (status = 'REJECTED' AND rejection_reason IS NOT NULL AND BTRIM(rejection_reason) <> '')))
    )
);

-- Latest submission of a user ("what is my status?") and the admin's newest-first pending list.
CREATE INDEX idx_realtor_license_owner ON realtor_license_verifications (user_id, id DESC);
CREATE INDEX idx_realtor_license_status ON realtor_license_verifications (status, id DESC);

-- A user can have at most one open submission; a second POST while pending is refused by the service (409)
-- and by the database if two requests race.
CREATE UNIQUE INDEX uq_realtor_license_one_pending
    ON realtor_license_verifications (user_id) WHERE status = 'PENDING_REVIEW';
