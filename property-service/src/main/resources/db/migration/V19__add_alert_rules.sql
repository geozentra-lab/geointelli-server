CREATE TABLE alert_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(120) NOT NULL CHECK (BTRIM(name) <> ''),
    event_type VARCHAR(30) NOT NULL CHECK (
        event_type IN ('NEW_MATCH', 'LISTING_PRICE_CHANGED', 'VALUATION_CHANGED')),
    property_id BIGINT REFERENCES properties(id) ON DELETE CASCADE,
    saved_search_id BIGINT REFERENCES saved_searches(id) ON DELETE CASCADE,
    cadence VARCHAR(20) NOT NULL DEFAULT 'DAILY' CHECK (cadence IN ('DAILY', 'WEEKLY')),
    paused BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_alert_rule_target CHECK (
        (property_id IS NOT NULL AND saved_search_id IS NULL)
        OR (property_id IS NULL AND saved_search_id IS NOT NULL)),
    CONSTRAINT ck_alert_rule_new_match CHECK (
        event_type <> 'NEW_MATCH' OR saved_search_id IS NOT NULL),
    CONSTRAINT uq_alert_rules_user_property_event UNIQUE (user_id, property_id, event_type),
    CONSTRAINT uq_alert_rules_user_search_event UNIQUE (user_id, saved_search_id, event_type)
);

CREATE INDEX idx_alert_rules_user_id ON alert_rules (user_id, id DESC);
CREATE INDEX idx_alert_rules_property_id ON alert_rules (property_id);
CREATE INDEX idx_alert_rules_saved_search_id ON alert_rules (saved_search_id);