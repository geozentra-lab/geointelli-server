-- V17 is reserved for holding financial records on the separate feature branch.
CREATE TABLE saved_searches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(120) NOT NULL CHECK (BTRIM(name) <> ''),
    filters JSONB NOT NULL,
    filters_version INTEGER NOT NULL DEFAULT 1 CHECK (filters_version > 0),
    cadence VARCHAR(20) NOT NULL DEFAULT 'DAILY' CHECK (cadence IN ('DAILY', 'WEEKLY')),
    paused BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_saved_searches_user_id ON saved_searches (user_id, id DESC);
