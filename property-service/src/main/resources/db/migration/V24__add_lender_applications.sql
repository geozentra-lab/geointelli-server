-- Explicit tenant membership; organization access is independent of later persona/role policies.
CREATE TABLE lender_organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL CHECK (TRIM(name) <> ''),
    owner_user_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_lender_organizations_owner ON lender_organizations(owner_user_id, id);

CREATE TABLE lender_organization_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES lender_organizations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    CONSTRAINT uq_lender_membership UNIQUE(organization_id, user_id)
);
CREATE INDEX idx_lender_members_user ON lender_organization_members(user_id, organization_id);

CREATE TABLE lender_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES lender_organizations(id),
    created_by_user_id BIGINT NOT NULL REFERENCES users(id),
    applicant_name VARCHAR(160) NOT NULL CHECK (TRIM(applicant_name) <> ''),
    applicant_email VARCHAR(254),
    property_id BIGINT REFERENCES properties(id) ON DELETE SET NULL,
    requested_amount NUMERIC(18,2) NOT NULL CHECK (requested_amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD' CHECK (currency = 'USD'),
    stage VARCHAR(30) NOT NULL DEFAULT 'DRAFT'
        CHECK (stage IN ('DRAFT','SUBMITTED','UNDER_REVIEW','APPROVED','FUNDED','REJECTED','WITHDRAWN')),
    approved_amount NUMERIC(18,2),
    funded_amount NUMERIC(18,2),
    approved_at TIMESTAMP WITH TIME ZONE,
    funded_at TIMESTAMP WITH TIME ZONE,
    notes VARCHAR(2000),
    source VARCHAR(80),
    external_id VARCHAR(160),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_lender_application_source UNIQUE(organization_id, source, external_id),
    CONSTRAINT ck_lender_source_pair CHECK (
        (source IS NULL AND external_id IS NULL) OR
        (source IS NOT NULL AND TRIM(source) <> '' AND external_id IS NOT NULL AND TRIM(external_id) <> '')),
    CONSTRAINT ck_lender_approval_pair CHECK (
        (approved_amount IS NULL AND approved_at IS NULL) OR
        (approved_amount IS NOT NULL AND approved_at IS NOT NULL AND approved_amount > 0 AND approved_amount <= requested_amount)),
    CONSTRAINT ck_lender_approval_stage CHECK (
        (stage IN ('APPROVED','FUNDED') AND approved_amount IS NOT NULL AND approved_at IS NOT NULL) OR
        (stage = 'WITHDRAWN') OR
        (stage NOT IN ('APPROVED','FUNDED','WITHDRAWN') AND approved_amount IS NULL AND approved_at IS NULL)),
    CONSTRAINT ck_lender_funding CHECK (
        (stage = 'FUNDED' AND funded_amount IS NOT NULL AND funded_at IS NOT NULL AND funded_amount > 0
            AND funded_amount <= approved_amount AND funded_at >= approved_at) OR
        (stage <> 'FUNDED' AND funded_amount IS NULL AND funded_at IS NULL))
);
CREATE INDEX idx_lender_applications_org_id ON lender_applications(organization_id, id DESC);
CREATE INDEX idx_lender_applications_org_stage ON lender_applications(organization_id, stage, id DESC);
CREATE INDEX idx_lender_applications_property ON lender_applications(property_id);
