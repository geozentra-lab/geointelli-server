CREATE TABLE holding_financial_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holding_id BIGINT NOT NULL REFERENCES portfolio_holdings(id) ON DELETE CASCADE,
    category VARCHAR(30) NOT NULL CHECK (category IN (
        'RENT', 'OTHER_INCOME', 'REPAIRS', 'MAINTENANCE', 'INSURANCE',
        'PROPERTY_TAX', 'HOA', 'UTILITIES', 'MANAGEMENT_FEE', 'MORTGAGE_PAYMENT', 'OTHER_EXPENSE')),
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD' CHECK (currency = 'USD'),
    transaction_date DATE NOT NULL,
    period_start DATE,
    period_end DATE,
    description VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_financial_record_period CHECK (
        (period_start IS NULL AND period_end IS NULL)
        OR (period_start IS NOT NULL AND period_end IS NOT NULL AND period_end >= period_start))
);

CREATE INDEX idx_financial_records_holding_date
    ON holding_financial_records (holding_id, transaction_date DESC, id DESC);
