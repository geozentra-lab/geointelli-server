CREATE TABLE portfolios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(120) NOT NULL CHECK (BTRIM(name) <> ''),
    description VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_portfolios_user_id ON portfolios (user_id, id DESC);

CREATE TABLE portfolio_holdings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
    property_id BIGINT NOT NULL REFERENCES properties(id),
    acquisition_date DATE,
    purchase_price NUMERIC(14,2) CHECK (purchase_price >= 0),
    acquisition_costs NUMERIC(14,2) CHECK (acquisition_costs >= 0),
    ownership_share_percent NUMERIC(5,2) NOT NULL DEFAULT 100
        CHECK (ownership_share_percent > 0 AND ownership_share_percent <= 100),
    financing_type VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN'
        CHECK (financing_type IN ('UNKNOWN', 'CASH', 'FINANCED')),
    loan_amount NUMERIC(14,2) CHECK (loan_amount >= 0),
    outstanding_balance NUMERIC(14,2) CHECK (outstanding_balance >= 0),
    balance_as_of_date DATE,
    interest_rate_percent NUMERIC(7,4) CHECK (interest_rate_percent >= 0 AND interest_rate_percent <= 100),
    loan_term_months INTEGER CHECK (loan_term_months BETWEEN 1 AND 600),
    monthly_payment NUMERIC(14,2) CHECK (monthly_payment >= 0),
    occupancy_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN'
        CHECK (occupancy_status IN ('UNKNOWN', 'OWNER_OCCUPIED', 'RENTED', 'VACANT')),
    monthly_rent NUMERIC(14,2) CHECK (monthly_rent >= 0),
    lease_start_date DATE,
    lease_end_date DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_portfolio_holdings_property UNIQUE (portfolio_id, property_id),
    CONSTRAINT ck_holding_balance_date CHECK (
        (outstanding_balance IS NULL AND balance_as_of_date IS NULL)
        OR (outstanding_balance IS NOT NULL AND balance_as_of_date IS NOT NULL)),
    CONSTRAINT ck_holding_lease_dates CHECK (
        lease_end_date IS NULL OR lease_start_date IS NULL OR lease_end_date >= lease_start_date),
    CONSTRAINT ck_holding_cash_financing CHECK (
        financing_type <> 'CASH' OR (
            COALESCE(loan_amount, 0) = 0 AND COALESCE(outstanding_balance, 0) = 0
            AND COALESCE(interest_rate_percent, 0) = 0 AND loan_term_months IS NULL
            AND COALESCE(monthly_payment, 0) = 0)),
    CONSTRAINT ck_holding_rental_occupancy CHECK (
        occupancy_status = 'RENTED' OR (
            COALESCE(monthly_rent, 0) = 0 AND lease_start_date IS NULL AND lease_end_date IS NULL))
);

CREATE INDEX idx_portfolio_holdings_portfolio_id ON portfolio_holdings (portfolio_id, id DESC);
CREATE INDEX idx_portfolio_holdings_property_id ON portfolio_holdings (property_id);
