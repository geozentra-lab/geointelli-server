-- V24 is reserved for the lender-applications branch.
-- Immutable submissions keep historical property/lead IDs; source deletion must not rewrite consent evidence.
CREATE TABLE property_contact_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_user_id BIGINT NOT NULL REFERENCES users(id),
    professional_user_id BIGINT NOT NULL REFERENCES users(id),
    property_id BIGINT NOT NULL CHECK (property_id > 0),
    lead_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED' CHECK (status = 'SUBMITTED'),
    contact_name VARCHAR(120) NOT NULL CHECK (TRIM(contact_name) <> ''),
    contact_email VARCHAR(254),
    contact_phone VARCHAR(40),
    message VARCHAR(2000),
    consent BOOLEAN NOT NULL CHECK (consent = TRUE),
    consent_version VARCHAR(80) NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL,
    request_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    CONSTRAINT uq_property_contact_request_key UNIQUE(requester_user_id, request_key),
    CONSTRAINT ck_property_contact_details CHECK (contact_email IS NOT NULL OR contact_phone IS NOT NULL)
);
CREATE INDEX idx_property_contact_professional ON property_contact_requests(professional_user_id, id DESC);

CREATE TABLE contact_request_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL UNIQUE REFERENCES property_contact_requests(id),
    event_id VARCHAR(128) NOT NULL UNIQUE,
    event_json TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at TIMESTAMPTZ NOT NULL,
    last_error_code VARCHAR(80),
    sent_at TIMESTAMPTZ,
    CONSTRAINT ck_contact_outbox_sent CHECK ((status = 'SENT' AND sent_at IS NOT NULL)
        OR (status <> 'SENT' AND sent_at IS NULL))
);
CREATE INDEX idx_contact_outbox_due ON contact_request_outbox(status, next_attempt_at, id);
