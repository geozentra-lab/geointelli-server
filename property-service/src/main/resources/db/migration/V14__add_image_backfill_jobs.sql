CREATE TABLE image_backfill_jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    county_id BIGINT NOT NULL REFERENCES counties(id),
    status VARCHAR(20) NOT NULL,
    batch_size INTEGER NOT NULL CHECK (batch_size BETWEEN 1 AND 100),
    total INTEGER NOT NULL DEFAULT 0,
    processed INTEGER NOT NULL DEFAULT 0,
    completed INTEGER NOT NULL DEFAULT 0,
    skipped INTEGER NOT NULL DEFAULT 0,
    failed INTEGER NOT NULL DEFAULT 0,
    after_property_id BIGINT NOT NULL DEFAULT 0,
    last_property_id BIGINT NOT NULL DEFAULT 0,
    error_code VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    lease_expires_at TIMESTAMPTZ DEFAULT (CURRENT_TIMESTAMP + INTERVAL '10 minutes')
);

CREATE TABLE image_backfill_claims (
    property_id BIGINT PRIMARY KEY REFERENCES properties(id),
    job_id BIGINT NOT NULL REFERENCES image_backfill_jobs(id),
    status VARCHAR(20) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE image_backfill_results (
    job_id BIGINT NOT NULL REFERENCES image_backfill_jobs(id),
    property_id BIGINT NOT NULL REFERENCES properties(id),
    status VARCHAR(20) NOT NULL,
    reason VARCHAR(80),
    image_id BIGINT REFERENCES property_images(id),
    PRIMARY KEY (job_id, property_id)
);

ALTER TABLE property_images
    ADD COLUMN source VARCHAR(30),
    ADD COLUMN source_image_id VARCHAR(80),
    ADD COLUMN contributor TEXT,
    ADD COLUMN license VARCHAR(80),
    ADD COLUMN captured_at TIMESTAMPTZ,
    ADD COLUMN match_status VARCHAR(30),
    ADD COLUMN processing_note TEXT;

CREATE INDEX idx_image_backfill_jobs_created ON image_backfill_jobs(created_at DESC);
CREATE INDEX idx_image_backfill_claims_job ON image_backfill_claims(job_id);
CREATE INDEX idx_image_backfill_jobs_active_lease ON image_backfill_jobs(lease_expires_at)
    WHERE status IN ('QUEUED', 'RUNNING');
