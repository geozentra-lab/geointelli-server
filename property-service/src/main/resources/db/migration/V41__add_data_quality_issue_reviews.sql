-- Review and resolution of data-quality findings (SCRUM-92 / SCRUM-190).
-- The scanner of SCRUM-189 computes its findings on each request and never stores them; a finding is
-- identified by the reproducible reference RULE:entityType:entityId (for example SALE_DUPLICATE:SALE:9012).
-- This table is the review log of those findings. It is append-only: every review action inserts one row
-- recording the transition (from_status -> to_status), the reviewer, the time and the reason, so nothing a
-- reviewer wrote is ever overwritten. The current state of a finding is its newest row; a finding without
-- any row is OPEN. The source records (properties, sales, assessments) are never changed by a review.

CREATE TABLE data_quality_issue_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Reproducible reference of the finding, exactly as the scanner returns it
    issue_reference VARCHAR(80) NOT NULL,
    rule VARCHAR(40) NOT NULL CHECK (rule ~ '^[A-Z][A-Z0-9_]*$'),
    entity_type VARCHAR(20) NOT NULL CHECK (entity_type IN ('PROPERTY', 'SALE', 'ASSESSMENT')),
    entity_id BIGINT NOT NULL CHECK (entity_id > 0),
    -- Property concerned by the finding, copied at review time for grouping; no foreign key so the review
    -- history survives a later correction that deletes the source row
    property_id BIGINT,
    from_status VARCHAR(20) NOT NULL CHECK (from_status IN ('OPEN', 'IN_REVIEW', 'RESOLVED', 'IGNORED')),
    to_status VARCHAR(20) NOT NULL CHECK (to_status IN ('IN_REVIEW', 'RESOLVED', 'IGNORED', 'OPEN')),
    -- Why the reviewer moved the finding; required unless the finding is only taken into review
    reason VARCHAR(500),
    reviewed_by_user_id BIGINT NOT NULL REFERENCES users(id),
    reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- The reference is exactly rule:entityType:entityId, so the three columns and the reference never disagree
    CONSTRAINT ck_dq_review_reference CHECK (issue_reference = rule || ':' || entity_type || ':' || entity_id),
    -- A row records a real change; resolving, ignoring and reopening need a reason
    CONSTRAINT ck_dq_review_transition CHECK (
        from_status <> to_status
        AND (to_status = 'IN_REVIEW' OR (reason IS NOT NULL AND BTRIM(reason) <> ''))
    )
);

-- Current state of one finding (newest row) and the review status of a page of findings
CREATE INDEX idx_dq_reviews_reference ON data_quality_issue_reviews (issue_reference, id DESC);
-- Reviews of one property, whatever the rule
CREATE INDEX idx_dq_reviews_property ON data_quality_issue_reviews (property_id, id DESC);
