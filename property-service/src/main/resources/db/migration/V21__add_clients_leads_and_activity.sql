CREATE TABLE crm_clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(120) NOT NULL CHECK (BTRIM(name) <> ''),
    email VARCHAR(254),
    phone VARCHAR(40),
    notes VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_crm_client_owner_email UNIQUE (user_id, email),
    CONSTRAINT uq_crm_client_id_owner UNIQUE (id, user_id),
    CONSTRAINT ck_crm_client_email_normalized CHECK (email IS NULL OR (email = LOWER(BTRIM(email)) AND email <> '')),
    CONSTRAINT ck_crm_client_contact CHECK (email IS NOT NULL OR (phone IS NOT NULL AND BTRIM(phone) <> ''))
);
CREATE INDEX idx_crm_clients_owner ON crm_clients(user_id, id DESC);

CREATE TABLE crm_leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    client_id BIGINT NOT NULL,
    property_id BIGINT REFERENCES properties(id) ON DELETE SET NULL,
    title VARCHAR(160) NOT NULL CHECK (BTRIM(title) <> ''),
    source VARCHAR(80) NOT NULL CHECK (BTRIM(source) <> ''),
    stage VARCHAR(20) NOT NULL DEFAULT 'NEW' CHECK (stage IN ('NEW','CONTACTED','QUALIFIED','CONVERTED','LOST')),
    notes VARCHAR(2000),
    request_key VARCHAR(100) NOT NULL CHECK (BTRIM(request_key) <> ''),
    request_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_crm_lead_owned_client FOREIGN KEY (client_id, user_id) REFERENCES crm_clients(id, user_id),
    CONSTRAINT uq_crm_lead_submission UNIQUE (user_id, request_key)
);
CREATE INDEX idx_crm_leads_owner ON crm_leads(user_id, id DESC);
CREATE INDEX idx_crm_leads_owner_stage ON crm_leads(user_id, stage, id DESC);
CREATE INDEX idx_crm_leads_client ON crm_leads(client_id);
CREATE INDEX idx_crm_leads_property ON crm_leads(property_id);

-- Subject IDs are historical references, intentionally not cascading foreign keys:
-- deleting a client must not erase the owner's record of the deletion.
CREATE TABLE crm_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    client_id BIGINT NOT NULL,
    subject_type VARCHAR(20) NOT NULL CHECK (subject_type IN ('CLIENT','LEAD')),
    subject_id BIGINT NOT NULL,
    activity_type VARCHAR(40) NOT NULL CHECK (activity_type IN
        ('CLIENT_CREATED','CLIENT_UPDATED','CLIENT_DELETED','LEAD_CREATED','LEAD_UPDATED','LEAD_STAGE_CHANGED','NOTE_ADDED')),
    description VARCHAR(2000) NOT NULL CHECK (BTRIM(description) <> ''),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_crm_activity_owner ON crm_activities(user_id, id DESC);
CREATE INDEX idx_crm_activity_client ON crm_activities(user_id, client_id, id DESC);
CREATE INDEX idx_crm_activity_subject ON crm_activities(user_id, subject_type, subject_id, id DESC);
