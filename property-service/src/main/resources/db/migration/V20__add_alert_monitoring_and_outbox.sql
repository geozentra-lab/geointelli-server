CREATE TABLE alert_evaluation_states (
    rule_id BIGINT PRIMARY KEY REFERENCES alert_rules(id) ON DELETE CASCADE,
    generation BIGINT NOT NULL DEFAULT 0,
    baseline_generation BIGINT,
    baseline_hash VARCHAR(64),
    run_hash VARCHAR(64),
    run_stamp VARCHAR(160),
    cursor_id BIGINT NOT NULL DEFAULT 0,
    matched_count BIGINT NOT NULL DEFAULT 0,
    running BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(30) NOT NULL DEFAULT 'READY',
    started_at TIMESTAMPTZ,
    last_evaluated_at TIMESTAMPTZ,
    next_evaluation_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error_code VARCHAR(80),
    failure_count INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_alert_evaluation_due ON alert_evaluation_states(next_evaluation_at, rule_id);

-- Two generations are retained during a scan: last successful baseline and current staging.
-- Property IDs are observations, not foreign keys: deletion must not rewrite a historical baseline.
CREATE TABLE alert_match_memberships (
    rule_id BIGINT NOT NULL REFERENCES alert_rules(id) ON DELETE CASCADE,
    generation BIGINT NOT NULL,
    property_id BIGINT NOT NULL,
    PRIMARY KEY (rule_id, generation, property_id)
);

-- No rule FK: committed events must remain auditable after rule deletion.
-- The publisher cancels unsent events when their rule has been deleted.
CREATE TABLE alert_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT NOT NULL,
    generation BIGINT NOT NULL,
    saved_search_id BIGINT,
    property_id BIGINT,
    recipient_keycloak_id VARCHAR(255) NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','FAILED','CANCELLED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error_code VARCHAR(80),
    sent_at TIMESTAMPTZ,
    CONSTRAINT uq_alert_outbox_generation UNIQUE (rule_id, generation)
);
CREATE INDEX idx_alert_outbox_due ON alert_outbox(status, next_attempt_at, id);
CREATE INDEX idx_alert_outbox_rule ON alert_outbox(rule_id, status);
