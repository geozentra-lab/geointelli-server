-- Background job tracking for CSV imports and Miami-Dade API ingestion (SCRUM-188).
-- Jobs use UUIDs so they never collide with the numeric image_backfill_jobs IDs that the
-- admin import-job endpoints already expose. Written without partial indexes or JSONB so
-- the same script also runs on the H2 test database.

CREATE TABLE ingestion_jobs (
    id UUID PRIMARY KEY,
    job_type VARCHAR(40) NOT NULL,
    dataset VARCHAR(40) NOT NULL,
    status VARCHAR(20) NOT NULL,
    source_county VARCHAR(100),
    source_state VARCHAR(100),
    county_id BIGINT REFERENCES counties(id),
    total INTEGER NOT NULL DEFAULT 0,
    processed INTEGER NOT NULL DEFAULT 0,
    succeeded INTEGER NOT NULL DEFAULT 0,
    skipped INTEGER NOT NULL DEFAULT 0,
    failed INTEGER NOT NULL DEFAULT 0,
    current_step VARCHAR(120),
    checkpoint_json TEXT,
    parameters_json TEXT,
    input_storage VARCHAR(10) NOT NULL,
    input_location VARCHAR(500),
    input_scope VARCHAR(120),
    worker_id VARCHAR(120),
    lease_expires_at TIMESTAMP WITH TIME ZONE,
    attempt INTEGER NOT NULL DEFAULT 1,
    retry_of_job_id UUID REFERENCES ingestion_jobs(id),
    created_by VARCHAR(120),
    error_code VARCHAR(80),
    error_message VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_ingestion_jobs_status CHECK (status IN ('QUEUED', 'RUNNING', 'COMPLETED', 'PARTIAL', 'FAILED', 'INTERRUPTED')),
    CONSTRAINT ck_ingestion_jobs_input_storage CHECK (input_storage IN ('NONE', 'S3', 'LOCAL')),
    CONSTRAINT ck_ingestion_jobs_counters CHECK (processed = succeeded + skipped + failed)
);

-- Newest-first listing and the poller's QUEUED scan.
CREATE INDEX idx_ingestion_jobs_created_at ON ingestion_jobs (created_at DESC);
CREATE INDEX idx_ingestion_jobs_status_lease ON ingestion_jobs (status, lease_expires_at);
-- One active Miami-Dade job per dataset, and "is there an active retry of job X".
CREATE INDEX idx_ingestion_jobs_dataset_status ON ingestion_jobs (dataset, status);
CREATE INDEX idx_ingestion_jobs_retry_of ON ingestion_jobs (retry_of_job_id);

-- Records that failed or were skipped, kept for the admin detail view; capped per job by the application.
CREATE TABLE ingestion_job_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id UUID NOT NULL REFERENCES ingestion_jobs(id),
    item_key VARCHAR(160) NOT NULL,
    status VARCHAR(20) NOT NULL,
    reason VARCHAR(80),
    message VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_ingestion_job_items_status CHECK (status IN ('FAILED', 'SKIPPED'))
);

CREATE INDEX idx_ingestion_job_items_job ON ingestion_job_items (job_id, id);
