-- Saved analysis scenarios (SCRUM-147): user-supplied assumptions only, never calculation results
-- and never property facts. Owned by one user; same conventions as saved_searches (V18).
CREATE TABLE scenarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    property_id BIGINT REFERENCES properties(id) ON DELETE SET NULL,
    name VARCHAR(120) NOT NULL CHECK (BTRIM(name) <> ''),
    scenario_type VARCHAR(30) NOT NULL CHECK (scenario_type IN ('INVESTMENT')),
    input_version INTEGER NOT NULL DEFAULT 1 CHECK (input_version > 0),
    assumptions JSONB NOT NULL CHECK (jsonb_typeof(assumptions) = 'object'),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- "My scenarios, newest first" (bounded listing)
CREATE INDEX idx_scenarios_user_id ON scenarios (user_id, id DESC);
