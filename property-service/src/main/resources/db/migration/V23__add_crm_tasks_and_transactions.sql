-- Existing CRM migration V21 uses PostgreSQL's generated CHECK constraint names.
ALTER TABLE crm_activities DROP CONSTRAINT crm_activities_subject_type_check;
ALTER TABLE crm_activities DROP CONSTRAINT crm_activities_activity_type_check;
ALTER TABLE crm_activities ALTER COLUMN client_id DROP NOT NULL;
ALTER TABLE crm_activities ADD CONSTRAINT crm_activities_subject_type_check
    CHECK (subject_type IN ('CLIENT','LEAD','TASK','TRANSACTION'));
ALTER TABLE crm_activities ADD CONSTRAINT crm_activities_activity_type_check CHECK (activity_type IN (
    'CLIENT_CREATED','CLIENT_UPDATED','CLIENT_DELETED','LEAD_CREATED','LEAD_UPDATED','LEAD_STAGE_CHANGED','NOTE_ADDED',
    'TASK_CREATED','TASK_UPDATED','TASK_STATUS_CHANGED','TASK_DELETED',
    'TRANSACTION_CREATED','TRANSACTION_UPDATED','TRANSACTION_STAGE_CHANGED'));

ALTER TABLE crm_leads ADD CONSTRAINT uq_crm_lead_id_client_owner UNIQUE (id, client_id, user_id);

CREATE TABLE crm_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    client_id BIGINT NOT NULL,
    lead_id BIGINT,
    -- A deal is a sale record for one property, so it blocks deleting that property.
    property_id BIGINT NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
    title VARCHAR(160) NOT NULL CHECK (BTRIM(title) <> ''),
    description VARCHAR(2000),
    stage VARCHAR(30) NOT NULL DEFAULT 'PROSPECT'
        CHECK (stage IN ('PROSPECT','VIEWING','OFFER','UNDER_CONTRACT','CLOSED','CANCELLED')),
    expected_close_date DATE,
    closed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_crm_transaction_client FOREIGN KEY(client_id, user_id) REFERENCES crm_clients(id, user_id),
    CONSTRAINT fk_crm_transaction_lead FOREIGN KEY(lead_id, client_id, user_id) REFERENCES crm_leads(id, client_id, user_id),
    CONSTRAINT uq_crm_transaction_id_client_owner UNIQUE(id, client_id, user_id),
    CONSTRAINT ck_crm_transaction_closed CHECK ((stage = 'CLOSED' AND closed_at IS NOT NULL)
        OR (stage <> 'CLOSED' AND closed_at IS NULL))
);
CREATE INDEX idx_crm_transactions_owner_stage ON crm_transactions(user_id, stage, id DESC);
CREATE INDEX idx_crm_transactions_owner ON crm_transactions(user_id, id DESC);
CREATE INDEX idx_crm_transactions_client ON crm_transactions(client_id);
CREATE INDEX idx_crm_transactions_lead ON crm_transactions(lead_id);
CREATE INDEX idx_crm_transactions_property ON crm_transactions(property_id);

CREATE TABLE crm_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    client_id BIGINT,
    lead_id BIGINT,
    property_id BIGINT REFERENCES properties(id) ON DELETE SET NULL,
    transaction_id BIGINT,
    title VARCHAR(160) NOT NULL CHECK (BTRIM(title) <> ''),
    description VARCHAR(2000),
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','IN_PROGRESS','COMPLETED','CANCELLED')),
    due_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_crm_task_client FOREIGN KEY(client_id, user_id) REFERENCES crm_clients(id, user_id),
    CONSTRAINT fk_crm_task_lead FOREIGN KEY(lead_id, client_id, user_id) REFERENCES crm_leads(id, client_id, user_id),
    CONSTRAINT fk_crm_task_transaction FOREIGN KEY(transaction_id, client_id, user_id)
        REFERENCES crm_transactions(id, client_id, user_id),
    CONSTRAINT ck_crm_task_linked_client CHECK ((lead_id IS NULL AND transaction_id IS NULL) OR client_id IS NOT NULL),
    CONSTRAINT ck_crm_task_completed CHECK ((status = 'COMPLETED' AND completed_at IS NOT NULL)
        OR (status <> 'COMPLETED' AND completed_at IS NULL))
);
CREATE INDEX idx_crm_tasks_owner ON crm_tasks(user_id, id DESC);
CREATE INDEX idx_crm_tasks_owner_status_due ON crm_tasks(user_id, status, due_at);
CREATE INDEX idx_crm_tasks_client ON crm_tasks(client_id);
CREATE INDEX idx_crm_tasks_lead ON crm_tasks(lead_id);
CREATE INDEX idx_crm_tasks_transaction ON crm_tasks(transaction_id);
CREATE INDEX idx_crm_tasks_property ON crm_tasks(property_id);
