-- SCRUM-59 integration contract v1 (2026-11-09). PROPOSAL for property-service; Java/Flyway owns this schema: copy it into the next free
-- Flyway version (V33 at the time of writing; V32 is add_comparable_candidate_indexes). geointelli-models
-- never runs this file against a shared database; its tests apply it to a disposable database only.
-- Python checks that these objects exist before publishing and refuses to publish otherwise.
--
-- Ownership:
--   property_valuation_runs, property_value_prediction_history  written by Python (publisher), read by Java
--   property_value_predictions (existing)                       written by Python (publisher), read by Java
--   property_valuation_refresh_requests                         Java inserts (enqueue); Python claims/updates

-- ---------------------------------------------------------------------------------------------------
-- 1) Published runs. One row per published run, inserted in the publish transaction, never updated.
-- ---------------------------------------------------------------------------------------------------
CREATE TABLE property_valuation_runs (
    run_id               VARCHAR(32)  PRIMARY KEY,
    -- FULL: whole supported market. TARGETED: listed properties (refresh). REGISTERED: a run published
    -- before history existed, registered later from its retained manifest.
    run_kind             VARCHAR(16)  NOT NULL,
    as_of                DATE         NOT NULL,                -- valuation date (= prediction_date)
    data_through         DATE,                                 -- last sale in the market data
    model_version        VARCHAR(32)  NOT NULL,
    valuation_method     VARCHAR(64)  NOT NULL,
    -- When the property-specific inputs were read. A row only replaces a current row whose run has an
    -- older or equal snapshot. NULL = unknown (treated as older than any known snapshot).
    source_snapshot_at   TIMESTAMPTZ,
    reference_run_id     VARCHAR(32)  REFERENCES property_valuation_runs (run_id),  -- TARGETED: centring source
    scope_json           TEXT         NOT NULL,                -- {"type":"FULL_MARKET"} | {"type":"PROPERTIES","count":n,"sha256":..}
    request_ids_json     TEXT,                                 -- refresh requests answered by this run (JSON array)
    row_count            INTEGER      NOT NULL,                -- rows in the run output
    published_count      INTEGER      NOT NULL,                -- rows that became current
    skipped_stale_count  INTEGER      NOT NULL,                -- rows not published: a newer snapshot was current
    retired_count        INTEGER      NOT NULL,                -- current rows removed (property no longer modelled)
    content_sha256       CHAR(64)     NOT NULL,                -- SHA-256 of the run's predictions.csv
    manifest_path        VARCHAR(300) NOT NULL,                -- relative to the geointelli-models root
    manifest_sha256      CHAR(64)     NOT NULL,
    inputs_sha256        CHAR(64),                             -- SHA-256 of inputs.joblib (NULL if not retained)
    publisher            VARCHAR(120) NOT NULL,
    scored_at            TIMESTAMPTZ  NOT NULL,                -- when the run was computed (manifest)
    published_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_property_valuation_runs_kind CHECK (run_kind IN ('FULL', 'TARGETED', 'REGISTERED')),
    CONSTRAINT ck_property_valuation_runs_counts CHECK (published_count + skipped_stale_count <= row_count)
);
CREATE INDEX idx_property_valuation_runs_published ON property_valuation_runs (published_at DESC);
CREATE INDEX idx_property_valuation_runs_kind ON property_valuation_runs (run_kind, published_at DESC);

-- ---------------------------------------------------------------------------------------------------
-- 2) Immutable valuation versions. Every row that becomes current is archived here in the same
--    transaction; current rows that predate history are archived (SEEDED_CURRENT) before replacement.
-- ---------------------------------------------------------------------------------------------------
CREATE TABLE property_value_prediction_history (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id              BIGINT       NOT NULL,
    -- Run that produced the row. PUBLISHED rows always reference property_valuation_runs (checked by the
    -- publisher in the same transaction). SEEDED_CURRENT rows keep the run id found on the current row
    -- verbatim, even when that run could not be registered (no FK for that reason); NULL if it had none.
    run_id                   VARCHAR(32),
    provenance               VARCHAR(20)  NOT NULL,            -- PUBLISHED | SEEDED_CURRENT
    -- same meaning and types as property_value_predictions
    predicted_price          NUMERIC,
    predicted_price_low      NUMERIC,
    predicted_price_high     NUMERIC,
    predicted_price_low_90   NUMERIC,
    predicted_price_high_90  NUMERIC,
    confidence               VARCHAR(10),
    confidence_score         INTEGER,
    has_sale_history         BOOLEAN,
    last_sale_price          NUMERIC,
    last_sale_date           DATE,
    forecast_1y              NUMERIC,
    forecast_1y_low          NUMERIC,
    forecast_1y_high         NUMERIC,
    unchanged_home_value_1y  NUMERIC,
    forecast_3y              NUMERIC,
    forecast_3y_low          NUMERIC,
    forecast_3y_high         NUMERIC,
    forecast_7y              NUMERIC,
    forecast_7y_low          NUMERIC,
    forecast_7y_high         NUMERIC,
    market_outlook_1y_pct    DOUBLE PRECISION,
    prediction_date          DATE,
    data_through             DATE,
    model_version            VARCHAR(32),
    notes                    TEXT,
    valuation_status         VARCHAR(12),
    status_reasons           TEXT,
    valuation_method         VARCHAR(64),
    valuation_factors        TEXT,
    input_hash               VARCHAR(16),
    -- Frozen model evidence (JSON): last sale and the nearby-sales summary the model used. NULL for
    -- SEEDED_CURRENT rows whose run did not record it. Never rebuilt from today's sales.
    evidence                 TEXT,
    row_sha256               CHAR(64)     NOT NULL,            -- hash of the published row content
    scored_at                TIMESTAMPTZ,                      -- when the run computed it (NULL if unknown)
    loaded_at                TIMESTAMPTZ  NOT NULL,            -- when it became current (original created_at for seeded rows)
    archived_at              TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pvp_history_provenance CHECK (provenance IN ('PUBLISHED', 'SEEDED_CURRENT')),
    CONSTRAINT ck_pvp_history_run CHECK (provenance = 'SEEDED_CURRENT' OR run_id IS NOT NULL)
);
-- Stable identity: one version per property and run (retries cannot add a second one).
CREATE UNIQUE INDEX ux_pvp_history_property_run ON property_value_prediction_history (property_id, run_id);
-- Seeded rows without a run id are identified by their original load time (no invented run ids).
CREATE UNIQUE INDEX ux_pvp_history_seeded_no_run ON property_value_prediction_history (property_id, loaded_at)
    WHERE run_id IS NULL;
CREATE INDEX idx_pvp_history_property_date ON property_value_prediction_history (property_id, prediction_date DESC, id DESC);
CREATE INDEX idx_pvp_history_run ON property_value_prediction_history (run_id);

CREATE OR REPLACE FUNCTION forbid_valuation_history_change() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME USING ERRCODE = 'integrity_constraint_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pvp_history_immutable BEFORE UPDATE OR DELETE ON property_value_prediction_history
    FOR EACH ROW EXECUTE FUNCTION forbid_valuation_history_change();
CREATE TRIGGER trg_property_valuation_runs_immutable BEFORE UPDATE OR DELETE ON property_valuation_runs
    FOR EACH ROW EXECUTE FUNCTION forbid_valuation_history_change();

-- ---------------------------------------------------------------------------------------------------
-- 3) Current table: at most one current row per property (already true in the data; now enforced).
--    idx_property_value_predictions_property_id (non-unique) becomes redundant and may be dropped.
-- ---------------------------------------------------------------------------------------------------
CREATE UNIQUE INDEX ux_property_value_predictions_property_id ON property_value_predictions (property_id);

-- ---------------------------------------------------------------------------------------------------
-- 4) Durable refresh requests (transactional outbox). Java inserts a row in the SAME transaction as the
--    verified sale / property change, with INSERT ... ON CONFLICT (event_key) DO NOTHING.
-- ---------------------------------------------------------------------------------------------------
CREATE TABLE property_valuation_refresh_requests (
    request_id         UUID         PRIMARY KEY,
    -- Idempotency key, unique forever. Must identify the change itself, including its version, e.g.
    -- SALE:<sale_id>:<sales.updated_at epoch ms>, PROPERTY:<property_id>:<source version>, MODEL:<run_id>:<property_id>.
    event_key          VARCHAR(200) NOT NULL,
    trigger_type       VARCHAR(30)  NOT NULL,      -- SALE_CHANGE | PROPERTY_CHANGE | MODEL_PUBLICATION
    scope_type         VARCHAR(20)  NOT NULL,      -- PROPERTY | FULL_MARKET
    property_id        BIGINT,                     -- required for PROPERTY scope (the changed / sold property)
    sale_id            BIGINT,                     -- SALE_CHANGE: the sale row that changed
    model_version      VARCHAR(32),                -- MODEL_PUBLICATION: model the refresh is for
    source_version     VARCHAR(64),                -- version of the changed source record (informational)
    -- Database time of the source change. Leave it to the DEFAULT (or now()) in the enqueue transaction;
    -- never an application clock: the worker waits until its snapshot is at least this time.
    source_changed_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    outcome            VARCHAR(20),                -- set with COMPLETED: PUBLISHED | SUPERSEDED | NOT_MODELLED
    attempts           INTEGER      NOT NULL DEFAULT 0,
    max_attempts       INTEGER      NOT NULL DEFAULT 5,
    next_attempt_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_owner        VARCHAR(120),
    lease_token        UUID,
    lease_expires_at   TIMESTAMPTZ,
    run_id             VARCHAR(32),                -- run prepared for / published by this request
    last_error_code    VARCHAR(80),                -- safe code only, never a message with data or credentials
    last_error_at      TIMESTAMPTZ,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at         TIMESTAMPTZ,
    completed_at       TIMESTAMPTZ,
    CONSTRAINT uq_valuation_refresh_event UNIQUE (event_key),
    CONSTRAINT ck_valuation_refresh_trigger CHECK (trigger_type IN ('SALE_CHANGE', 'PROPERTY_CHANGE', 'MODEL_PUBLICATION')),
    CONSTRAINT ck_valuation_refresh_scope CHECK (scope_type IN ('PROPERTY', 'FULL_MARKET')),
    CONSTRAINT ck_valuation_refresh_scope_property CHECK (scope_type <> 'PROPERTY' OR property_id IS NOT NULL),
    CONSTRAINT ck_valuation_refresh_status CHECK (status IN ('PENDING', 'LEASED', 'COMPLETED', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_valuation_refresh_outcome CHECK (outcome IS NULL OR outcome IN ('PUBLISHED', 'SUPERSEDED', 'NOT_MODELLED')),
    CONSTRAINT ck_valuation_refresh_lease CHECK (status <> 'LEASED' OR (lease_token IS NOT NULL AND lease_expires_at IS NOT NULL)),
    CONSTRAINT ck_valuation_refresh_done CHECK (status <> 'COMPLETED' OR (outcome IS NOT NULL AND completed_at IS NOT NULL))
);
CREATE INDEX idx_valuation_refresh_due ON property_valuation_refresh_requests (status, next_attempt_at, created_at);
CREATE INDEX idx_valuation_refresh_lease ON property_valuation_refresh_requests (status, lease_expires_at);
CREATE INDEX idx_valuation_refresh_property ON property_valuation_refresh_requests (property_id, status);
