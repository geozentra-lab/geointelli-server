ALTER TABLE notifications ADD COLUMN in_app_visible BOOLEAN NOT NULL DEFAULT TRUE;
CREATE INDEX idx_notifications_visible_recipient ON notifications(recipient_keycloak_id,created_at DESC,id DESC) WHERE in_app_visible;

CREATE TABLE notification_preferences (
    recipient_keycloak_id VARCHAR(255) PRIMARY KEY,
    in_app_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    email_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    new_match_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    email_cadence VARCHAR(12) NOT NULL DEFAULT 'DAILY' CHECK (email_cadence IN ('IMMEDIATE','DAILY','WEEKLY')),
    email_address VARCHAR(254),
    next_email_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL,
    CHECK (NOT email_enabled OR (email_address IS NOT NULL AND next_email_at IS NOT NULL))
);

CREATE TABLE notification_email_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_keycloak_id VARCHAR(255) NOT NULL REFERENCES notification_preferences(recipient_keycloak_id),
    recipient_email VARCHAR(254) NOT NULL,
    cadence VARCHAR(12) NOT NULL,
    subject VARCHAR(160) NOT NULL,
    body TEXT NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('SENDING','RETRY','ACCEPTED','FAILED','UNKNOWN','SUPPRESSED')),
    attempts INTEGER NOT NULL DEFAULT 1,
    provider_message_id VARCHAR(255),
    last_error_code VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    lease_expires_at TIMESTAMPTZ,
    accepted_at TIMESTAMPTZ
);
CREATE INDEX idx_notification_email_retry ON notification_email_deliveries(recipient_keycloak_id,next_attempt_at,id) WHERE status='RETRY';
CREATE INDEX idx_notification_email_lease ON notification_email_deliveries(lease_expires_at,id) WHERE status='SENDING';
CREATE INDEX idx_notification_email_owner ON notification_email_deliveries(recipient_keycloak_id,created_at DESC,id DESC);

CREATE TABLE notification_email_queue (
    notification_id BIGINT PRIMARY KEY REFERENCES notifications(id),
    recipient_keycloak_id VARCHAR(255) NOT NULL REFERENCES notification_preferences(recipient_keycloak_id),
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','ASSIGNED','SUPPRESSED')),
    delivery_id BIGINT REFERENCES notification_email_deliveries(id),
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_notification_email_pending ON notification_email_queue(recipient_keycloak_id,created_at,notification_id) WHERE status='PENDING';
CREATE INDEX idx_notification_preferences_due ON notification_preferences(next_email_at,recipient_keycloak_id) WHERE email_enabled;
