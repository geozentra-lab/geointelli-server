-- Notification-service owns these tables. No property-service database references.
CREATE TABLE consumed_alert_events (
    event_id VARCHAR(128) PRIMARY KEY,
    source VARCHAR(40) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    received_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(128) NOT NULL UNIQUE REFERENCES consumed_alert_events(event_id),
    recipient_keycloak_id VARCHAR(255) NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    alert_rule_id BIGINT NOT NULL,
    saved_search_id BIGINT,
    property_id BIGINT,
    source_change_id VARCHAR(160) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    payload JSONB NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    read_at TIMESTAMPTZ
);
CREATE INDEX idx_notifications_recipient_recent ON notifications(recipient_keycloak_id,created_at DESC,id DESC);
CREATE INDEX idx_notifications_recipient_unread ON notifications(recipient_keycloak_id,created_at DESC,id DESC) WHERE read_at IS NULL;
